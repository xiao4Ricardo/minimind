def rep_rate(text, n=3):
    """3-gram 复读率，与旧 20 题基准同口径，保证历史结果可比"""
    t = re.findall(r"\w+|[^\w\s]", text.lower())
    g = [tuple(t[i:i + n]) for i in range(len(t) - n + 1)]
    return (len(g) - len(set(g))) / len(g) if g else 0.0


def zh_ratio(text):
    if not text:
        return 0.0
    return sum(1 for c in text if '一' <= c <= '鿿') / len(text)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--weights", nargs="*", default=None,
                   help="形如 full_sft:0 grpo:0；缺省测全部")
    p.add_argument("--max_new_tokens", type=int, default=256)
    p.add_argument("--out", default="evals/bench200_raw.json")
    args = p.parse_args()

    tok = AutoTokenizer.from_pretrained(os.path.join(ROOT, "model"))
    if args.weights:
        targets = []
        for spec in args.weights:
            w, moe = spec.split(":")
            targets.append((w, f"{w}_768{'_moe' if int(moe) else ''}.pth", int(moe)))
    else:
        targets = ALL_WEIGHTS

    cats = [c for c, _ in QUESTIONS]
    qs = [q for _, q in QUESTIONS]
    print(f"题库：{len(qs)} 题 / {len(set(cats))} 类  贪心解码 max_new_tokens={args.max_new_tokens}\n", flush=True)

    results = {}
    for name, fn, moe in targets:
        path = os.path.join(ROOT, "out", fn)
        if not os.path.exists(path):
            print(f"  ⚠ 跳过 {name}：{fn} 不存在")
            continue
        cfg = MiniMindConfig(hidden_size=768, num_hidden_layers=8, use_moe=bool(moe))
        m = MiniMindForCausalLM(cfg)
        miss, _ = m.load_state_dict(torch.load(path, map_location="cpu"), strict=False)
        real = [k for k in miss if "freqs_c" not in k and "mask" not in k]
        if real:
            print(f"  ⚠ {name} 缺失 {len(real)} 个权重键，例 {real[:2]}")
        m = m.to(DEV).eval().requires_grad_(False)

        outs, t0 = [], time.time()
        for q in qs:
            prompt = tok.apply_chat_template([{"role": "user", "content": q}],
                                             tokenize=False, add_generation_prompt=True)
            ids = torch.tensor([tok(prompt, add_special_tokens=False).input_ids], device=DEV)
            with torch.no_grad():
                o = m.generate(ids, max_new_tokens=args.max_new_tokens, do_sample=False,
                               pad_token_id=tok.pad_token_id, eos_token_id=tok.eos_token_id)
            gen = o[0][len(ids[0]):]
            txt = tok.decode(gen, skip_special_tokens=True).strip()
            outs.append({"text": txt, "n_tok": int(gen.numel())})
        dt = time.time() - t0
        results[name] = outs
        rr = np.mean([rep_rate(o["text"]) for o in outs])
        print(f"  {name:<14} 完成  复读率 {rr:.1%}  平均长度 {np.mean([len(o['text']) for o in outs]):.0f}  "
              f"({dt/len(qs):.2f} s/题, 共 {dt/60:.1f} min)", flush=True)
        del m
        torch.cuda.empty_cache()

    with open(os.path.join(ROOT, args.out), "w", encoding="utf-8") as f:
        json.dump({"questions": [{"cat": c, "q": q} for c, q in QUESTIONS],
                   "results": results, "max_new_tokens": args.max_new_tokens}, f, ensure_ascii=False)
    print(f"\n原始输出已保存到 {args.out}（供后续统计与复核）")


